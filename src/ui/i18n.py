def resolve_language(language: str) -> str:
    if language in {LANGUAGE_EN, LANGUAGE_ZH}:
        return language
    return LANGUAGE_EN


class Translator:
    def __init__(self, language: str = LANGUAGE_EN):
        self.language = language

    def set_language(self, language: str) -> None:
        self.language = language if language in LANGUAGE_OPTIONS else LANGUAGE_EN

    def text(self, key: str, **kwargs: object) -> str:
        resolved = resolve_language(self.language)
        template = TRANSLATIONS.get(resolved, TRANSLATIONS[LANGUAGE_EN]).get(
            key,
            TRANSLATIONS[LANGUAGE_EN].get(key, key),
        )
        return template.format(**kwargs)
